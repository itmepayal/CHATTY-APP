export const defaultTheme: ThemeName = "brand";

export const getTheme = (themeName: ThemeName): AppColors =>
  themes[themeName] as unknown as AppColors;

export const getColors = (themeName: ThemeName) => {
  const t = getTheme(themeName);
  return {
    primary: t.primary,
    primaryDark: t.primaryDark,
    primaryLight: t.primaryLight,
    gradientTop: t.gradientTop,
    gradientBottom: t.gradientBottom,
    bg: t.background,
    text: t.text,
    muted: t.muted,
    border: t.border,
    inputBg: t.input,
  };
};

